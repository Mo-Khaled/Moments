"""Builds the hero gift-box brand assets from the identity kit (unzipped OUTSIDE the repo), so only what is needed enters assets/.
  python scripts/prepare-hero-box.py <path to MOMENTS-Identity folder>
Writes:
  assets/hero-box-pattern.svg - one tile of the signature pattern (the icon, half-drop repeat), tone-on-tone: fill #4E2E4D, the exact
                                 motif colour of 05-Brand-Elements/patterns/signature-plum.svg (the guide: patterns are always close
                                 to their background). The kit's pattern files are 253 KB each; this tile is a few KB.
  snippets/hero-box-logo.liquid - the icon with the English wordmark, or the Arabic wordmark on Arabic pages; fill currentColor.
"""
import re, sys, pathlib
kit = pathlib.Path(sys.argv[1])
root = pathlib.Path(__file__).resolve().parent.parent

def inner(svg_path):
    s = svg_path.read_text(encoding='utf8')
    vb = re.search(r'viewBox="([^"]+)"', s).group(1)
    body = re.search(r'<g fill="#FFFFFF">(.*)</g>\s*</svg>', s, re.S).group(1)
    body = re.sub(r'\s+', ' ', body).replace('> <', '><').strip()
    return vb, body

icon_vb, icon = inner(kit / '01-Logo/5-icon/MOMENTS-icon-white.svg')
en_vb, en = inner(kit / '01-Logo/3-wordmark-en/MOMENTS-wordmark-en-white.svg')
ar_vb, ar = inner(kit / '01-Logo/4-wordmark-ar/MOMENTS-wordmark-ar-white.svg')
iw = float(icon_vb.split()[2])

# pattern tile: 96 x 96, one motif at the centre of each half-drop cell
size, motif = 96, 40
k = motif / iw
cells = [(size / 4, size / 4), (size * 3 / 4, size * 3 / 4)]
uses = ''.join(f'<use href="#m" transform="translate({x - motif / 2:.2f},{y - motif / 2:.2f}) scale({k:.5f})"/>' for x, y in cells)
pattern = f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 {size} {size}"><defs><g id="m">{icon}</g></defs><g fill="#4E2E4D">{uses}</g></svg>\n'
(root / 'assets/hero-box-pattern.svg').write_text(pattern, encoding='utf8')

snippet = f'''{{%- doc -%}}
  The MOMENTS logo for the gift-box lid (sections/hero-gift-box.liquid): the icon over the English wordmark, or over the Arabic
  wordmark on Arabic pages. Paths from the identity kit (01-Logo), fill currentColor so the lid sets the colour (white or nude).
  Generated by scripts/prepare-hero-box.py; do not edit the paths by hand.

  @param {{string}} [label] - Accessible name. Leave empty when the logo is decorative.
{{%- enddoc -%}}
<span class="hgb-logo"{{% if label == blank %}} aria-hidden="true"{{% endif %}}>
  <svg class="hgb-logo__icon" viewBox="{icon_vb}" focusable="false"{{% if label != blank %}} role="img" aria-label="{{{{ label | escape }}}}"{{% endif %}}><g fill="currentColor">{icon}</g></svg>
  {{%- if request.locale.iso_code == 'ar' -%}}
    <svg class="hgb-logo__word hgb-logo__word--ar" viewBox="{ar_vb}" focusable="false" aria-hidden="true"><g fill="currentColor">{ar}</g></svg>
  {{%- else -%}}
    <svg class="hgb-logo__word" viewBox="{en_vb}" focusable="false" aria-hidden="true"><g fill="currentColor">{en}</g></svg>
  {{%- endif -%}}
</span>
'''
(root / 'snippets/hero-box-logo.liquid').write_text(snippet, encoding='utf8')
print('pattern', len(pattern), 'B; logo snippet', len(snippet), 'B')
