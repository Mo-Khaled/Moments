import { chromium } from 'playwright-core';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 3 });
await ctx.route(/kaspersky-labs|shopifysvc|monorail/, (r) => r.abort());
const page = await ctx.newPage();
await page.goto('https://momentseg.com/pages/make-a-bundle?pb=0', { waitUntil: 'domcontentloaded', timeout: 60000 });
await page.waitForTimeout(4500);
const g = page.locator('.card-gallery').nth(2); await g.scrollIntoViewIfNeeded(); await page.waitForTimeout(600);
const b = await g.boundingBox();
await page.screenshot({ path: 'docs/screenshots/bundle/probe-corners.png', clip: { x: b.x - 12, y: b.y - 12, width: b.width + 24, height: 110 } });
console.log(await g.evaluate((e) => { const out = []; for (const el of [e, ...e.querySelectorAll('*')]) { for (const p of ['::before', '::after']) { const s = getComputedStyle(el, p); if (s.content !== 'none' && s.content !== 'normal') out.push(`${el.tagName.toLowerCase()}.${String(el.className).split(' ')[0]}${p} content=${s.content} pos=${s.position} w=${s.width} h=${s.height} bg=${s.backgroundColor} border=${s.border}`); } } return out.join('\n'); }));
await browser.close();
