"""Writes snippets/moments-set-guide.liquid from data/descriptions/sets.json: for a product that holds several perfumes,
one "Understanding this scent" panel per perfume (snippets/scent-guide-panel.liquid).

A perfume with its own product is rendered from that product (all_products[handle]: its tags and note fields, the same
data as its own page). A perfume the store has no product for passes its notes from sets.json; its scent families come
from the same scoring as data/scent-scores.csv (Primary and Secondary), and season / time of day from the rule
fragrance-db.py uses for every product's season: and time: tags.

usage: python scripts/build-set-guide.py   (then push snippets/moments-set-guide.liquid)
"""
import importlib.util
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
spec = importlib.util.spec_from_file_location("scent_scores", os.path.join(ROOT, "scripts", "scent-scores.py"))
ss = importlib.util.module_from_spec(spec)
spec.loader.exec_module(ss)
bd, fdb = ss.bd, ss.fdb


def q(text):
    return "'" + str(text).replace("'", "’") + "'"


def main():
    sets = {k: v for k, v in json.load(open(os.path.join(ROOT, "data", "descriptions", "sets.json"), encoding="utf-8")).items()
            if not k.startswith("_")}
    _, _, _, _, note_ar, _, _, _ = bd.load()
    out = ["{%- doc -%}",
           "  GENERATED by scripts/build-set-guide.py from data/descriptions/sets.json. Do not edit by hand.",
           "  For a product that holds several perfumes: one scent-guide panel per perfume. Renders nothing for any other product.",
           "",
           "  @param {object} product - The product on the page.",
           "{%- enddoc -%}",
           "{%- case product.handle -%}"]
    for handle, spec in sets.items():
        if not isinstance(spec, dict):
            continue
        comps = spec["components"] if isinstance(spec["components"], list) else sets[spec["components"]]
        out.append(f"  {{%- when {q(handle)} -%}}")
        for c in comps:
            name = c["name_en"].split(" (")[0]
            name_ar = c["name_ar"].split(" (")[0]
            if "handle" in c:
                out.append(f"    {{%- render 'scent-guide-panel', perfume: all_products[{q(c['handle'])}], name: {q(name)}, name_ar: {q(name_ar)} -%}}")
                continue
            notes = c["notes"]
            scores = ss.family_scores(notes)
            primary = next(iter(scores), "")
            fams = [primary] + [f for f, v in scores.items() if f != primary and v >= ss.SECONDARY][:ss.MAX_SECONDARY]
            season, time = fdb.season(fams)
            tags = [f"family:{f}" for f in fams if f] + [f"note:{n}" for layer in ("top", "heart", "base") for n in notes.get(layer, [])]
            tags += [f"season:{season}"] if season else []
            tags += [f"time:{time}"] if time else []
            ar = {layer: "، ".join(note_ar.get(n, n) for n in notes.get(layer, [])) for layer in ("top", "heart", "base")}
            en = {layer: ", ".join(notes.get(layer, [])) for layer in ("top", "heart", "base")}
            out.append(f"    {{%- render 'scent-guide-panel', name: {q(name)}, name_ar: {q(name_ar)}, tags: {q(','.join(tags))},"
                       f" top: {q(en['top'])}, heart: {q(en['heart'])}, base: {q(en['base'])},"
                       f" top_ar: {q(ar['top'])}, heart_ar: {q(ar['heart'])}, base_ar: {q(ar['base'])} -%}}")
    out.append("{%- endcase -%}")
    path = os.path.join(ROOT, "snippets", "moments-set-guide.liquid")
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print("wrote", path)


if __name__ == "__main__":
    main()
